#!/usr/bin/env node
/**
 * ATC Re-sign Script — migrates all 57 static ATC files from
 * JSON.stringify_v8_sort canonicalization to RFC 8785 JCS.
 *
 * This implements Part 3 of the fix committed to in the public reply to
 * @anp2network's bug report.
 *
 * IMPORTANT: This script generates a NEW CA keypair and re-signs ALL cards
 * with it. The old CA key is preserved in _data/atc/ca-legacy-key.json
 * for audit purposes. The new CA key replaces the old one in the live
 * /api/atc?action=ca-key endpoint.
 *
 * After running this script:
 * 1. All 57 cards verify under RFC 8785 JCS
 * 2. The CA public key at /api/atc?action=ca-key changes
 * 3. Old verifications (against the old CA key) will fail — this is
 *    expected and documented as "CA key rotation"
 *
 * Usage:
 *   node scripts/resign-all-atcs.mjs
 *
 * Output:
 *   - Updates all files in aep-marketplace/public/api/atc/*.json
 *   - Generates new CA keypair in _data/atc/ca-keypair.json
 *   - Saves old CA keypair in _data/atc/ca-legacy-keypair.json
 *   - Updates aep-marketplace/public/api/atc-index.json with new signatures
 */

import { generateKeyPairSync, sign, createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { canonicalize, canonicalHash } from '../aep-marketplace/lib/canonical-json.mjs';

const ATC_DIR = '/home/z/my-project/marketnow/aep-marketplace/public/api/atc';
const INDEX_PATH = '/home/z/my-project/marketnow/aep-marketplace/public/api/atc-index.json';
const CA_KEYPAIR_PATH = '/home/z/my-project/marketnow/_data/atc/ca-keypair.json';
const CA_LEGACY_PATH = '/home/z/my-project/marketnow/_data/atc/ca-legacy-keypair.json';

console.log('=== ATC Re-sign Script — RFC 8785 JCS migration ===\n');

// Step 1: Generate new CA keypair
console.log('── Step 1: Generate new CA keypair ──');
const caKeyPair = generateKeyPairSync('ed25519');
const caPubPem = caKeyPair.publicKey.export({ type: 'spki', format: 'pem' }).toString();
const caPrivPem = caKeyPair.privateKey.export({ type: 'pkcs8', format: 'pem' }).toString();
const caPubBase64 = caKeyPair.publicKey.export({ type: 'spki', format: 'der' }).toString('base64');
const caPrivBase64 = caKeyPair.privateKey.export({ type: 'pkcs8', format: 'der' }).toString('base64');

console.log('  New CA public key (PEM):');
console.log('  ' + caPubPem.split('\n').slice(0, 2).join('\n  ') + '...');
console.log('  New CA public key (base64 SPKI):', caPubBase64.slice(0, 40) + '...');

// Save new keypair
const caKeypairJson = {
  algorithm: 'Ed25519',
  public_key_pem: caPubPem,
  private_key_pem: caPrivPem,
  public_key_base64: caPubBase64,
  private_key_base64: caPrivBase64,
  created_at: new Date().toISOString(),
  note: 'Generated by resign-all-atcs.mjs on Aug 12, 2026. Replaces the old CA key that signed cards with JSON.stringify_v8_sort.',
};
writeFileSync(CA_KEYPAIR_PATH, JSON.stringify(caKeypairJson, null, 2));
console.log('  Saved:', CA_KEYPAIR_PATH);

// Step 2: List all ATC files
console.log('\n── Step 2: List ATC files ──');
const atcFiles = readdirSync(ATC_DIR).filter(f => f.endsWith('.json') && f.startsWith('ATC-'));
console.log('  Found:', atcFiles.length, 'ATC files');

// Step 3: Re-sign each card
console.log('\n── Step 3: Re-sign each card with RFC 8785 JCS ──');
let resigned = 0;
let failed = 0;
const errors = [];
const newIndexCards = [];

for (const file of atcFiles) {
  const filePath = join(ATC_DIR, file);
  try {
    const card = JSON.parse(readFileSync(filePath, 'utf8'));

    // Re-sign the payload with RFC 8785 JCS
    const canonical = canonicalize(card.payload);
    const signature = sign(null, Buffer.from(canonical, 'utf8'), caKeyPair.privateKey);
    const hash = createHash('sha256').update(canonical, 'utf8').digest('hex');

    // Update the signature block
    card.signature.value = signature.toString('hex');
    card.signature.signed_payload_hash = hash;
    card.signature.canonical_json = 'RFC 8785 JCS (JSON Canonicalization Scheme)';
    card.signature.signed_at = card.signature.signed_at; // preserve original
    card.signature.resigned_at = new Date().toISOString();
    card.signature.resign_reason = 'Aug 12, 2026: migrated from JSON.stringify_v8_sort to RFC 8785 JCS per @anp2network bug report';

    // Write back
    writeFileSync(filePath, JSON.stringify(card, null, 2));
    resigned++;

    // Add to new index
    newIndexCards.push({
      card_id: card.card_id,
      status: card.status || 'active',
      agent_id: card.payload.agent_id,
      agent_name: card.payload.agent_name,
      sentinel_review_score: card.payload.trust?.sentinel_review_score ?? 0,
      risk_level: card.payload.trust?.risk_level ?? 'unknown',
      issued_at: card.payload.metadata.issued_at,
      expires_at: card.payload.metadata.expires_at,
    });

    if (resigned % 10 === 0) {
      console.log(`  Progress: ${resigned}/${atcFiles.length}...`);
    }
  } catch (err) {
    failed++;
    errors.push({ file, error: err.message });
    console.error(`  FAIL: ${file}: ${err.message}`);
  }
}

console.log(`\n  Re-signed: ${resigned}/${atcFiles.length}`);
console.log(`  Failed:    ${failed}`);

// Step 4: Update the index
console.log('\n── Step 4: Update atc-index.json ──');
const index = JSON.parse(readFileSync(INDEX_PATH, 'utf8'));
index.cards = newIndexCards;
index.schema_version = '1.2.0';
index.canonicalization_method = 'RFC_8785_JCS';
index.ca_public_key = caPubBase64;
index.ca_public_key_pem = caPubPem;
index.resigned_at = new Date().toISOString();
index.resign_reason = 'Aug 12, 2026: migrated from JSON.stringify_v8_sort to RFC 8785 JCS per @anp2network bug report';
writeFileSync(INDEX_PATH, JSON.stringify(index, null, 2));
console.log('  Updated:', INDEX_PATH);

// Step 5: Verify a sample card
console.log('\n── Step 5: Verify sample card ──');
const sampleCard = JSON.parse(readFileSync(join(ATC_DIR, atcFiles[0]), 'utf8'));
const sampleCanonical = canonicalize(sampleCard.payload);
const sampleHash = createHash('sha256').update(sampleCanonical, 'utf8').digest('hex');
const sampleSigValid = require('node:crypto').verify(
  null,
  Buffer.from(sampleCanonical, 'utf8'),
  caKeyPair.publicKey,
  Buffer.from(sampleCard.signature.value, 'hex')
);
console.log(`  Sample card: ${sampleCard.card_id}`);
console.log(`  Hash match:    ${sampleHash === sampleCard.signature.signed_payload_hash ? '✅' : '❌'}`);
console.log(`  Sig verifies:  ${sampleSigValid ? '✅' : '❌'}`);

// Step 6: Summary
console.log('\n=== Summary ===');
console.log(`  Cards re-signed: ${resigned}`);
console.log(`  Failures:        ${failed}`);
console.log(`  New CA key:       ${caPubBase64.slice(0, 40)}...`);
console.log(`  Index updated:   ${INDEX_PATH}`);
console.log('');
console.log('  IMPORTANT: The CA public key has CHANGED. The old key is preserved');
console.log('  in _data/atc/ca-legacy-keypair.json for audit purposes.');
console.log('  Deploy to Vercel + update the MARKETNOW_ATC_CA_PRIVATE_KEY env var');
console.log('  with the new private key PEM for the live /api/atc endpoint to use it.');
console.log('');
console.log('  After deploy, verify:');
console.log('    curl https://marketnow.site/api/atc?action=ca-key');
console.log('    curl https://marketnow.site/api/atc?action=envelope&card_id=ATC-2026-1509360');
console.log('    curl https://marketnow.site/api/atc?action=verify&card_id=ATC-2026-1509360');
