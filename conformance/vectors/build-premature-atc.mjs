#!/usr/bin/env node
// Build the premature-atc fixed vector (v1.3.3): properly signed by ca-test-2
// (pinned anchor, private key published in _test-ca-keys.json), active status,
// clean cryptography — the ONLY defect is a FUTURE issued_at (2030-01-01).
// The exact mirror of expired-atc (which fails only the upper bound).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash, createPrivateKey, sign as cryptoSign } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const VECTORS = join(__dirname, '../vectors');

const jcs = (v) => JSON.stringify(v, (k, x) =>
  (x !== null && typeof x === 'object' && !Array.isArray(x))
    ? Object.fromEntries(Object.entries(x).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
    : x);

const keys = JSON.parse(readFileSync(join(VECTORS, '_test-ca-keys.json'), 'utf8'));
const ca2 = keys.ca_test_2;
const ca2Spki = ca2.public_key_spki_b64;
const ca2Priv = createPrivateKey({ key: Buffer.from(ca2.private_key_pkcs8_b64, 'base64'), format: 'der', type: 'pkcs8' });

const card = {
  card_id: 'ATC-TEST-PREMATURE',
  status: 'active',
  payload: {
    card_id: 'ATC-TEST-PREMATURE',
    schema_version: '2.0.0',
    agent_id: 'test-agent-valid',
    agent_name: 'Valid Test Agent',
    identity: { public_key: ca2Spki, key_algorithm: 'Ed25519' },
    trust: {
      sentinel_review_score: 8,
      sentinel_score: 8,
      audit_layers_passed: { 'L1.5': true, 'L2.5': true },
      composite_trust: 8,
      risk_level: 'low',
    },
    capabilities: { provides: ['search', 'read'], protocol_language: 'mcp', translate: true },
    payment: { method: 'none', wallet_address: null },
    metadata: {
      issued_at: '2030-01-01T00:00:00Z',
      expires_at: '2032-01-01T00:00:00Z',
      issuer: 'MarketNow Sentinel Generator CA',
    },
  },
  signature: {
    algorithm: 'Ed25519 (RFC 8032)',
    value: '',
    signed_by: 'generated by generate-accept-vectors.mjs (ca-test-2, private key published)',
    signed_at: '2026-09-09T00:00:00Z',
    canonical_json: 'RFC_8785_JCS',
    ca_key_id: ca2Spki,
    evidence_hash: 'sha256:premature_test',
    policy_version: '2.0.0',
  },
};

const { signature, ...subtree } = card;
const canonical = jcs(subtree);
const buf = Buffer.from(canonical, 'utf8');
card.signature.value = cryptoSign(null, buf, ca2Priv).toString('hex');

writeFileSync(join(VECTORS, 'premature-atc.json'), JSON.stringify(card, null, 1) + '\n');
writeFileSync(join(VECTORS, 'premature-atc.canonical.txt'), canonical);
writeFileSync(join(VECTORS, 'premature-atc.sha256'), createHash('sha256').update(buf).digest('hex') + '\n');
writeFileSync(join(VECTORS, 'premature-atc.bytes.hex'), buf.toString('hex') + '\n');
writeFileSync(join(VECTORS, 'premature-atc.bytes.base64'), buf.toString('base64') + '\n');

console.log('premature-atc vector written');
console.log(`  canonical bytes: ${buf.length}`);
console.log(`  sha256: ${createHash('sha256').update(buf).digest('hex')}`);
console.log(`  issued_at: ${card.payload.metadata.issued_at} | expires_at: ${card.payload.metadata.expires_at}`);
